// 自由文本分类归一到 12 类（Workspace 的类型是自由输入）
export function normalizeGenre(genre) {
  const g = String(genre || '').trim()
  if (!g) return ''
  if (STYLE_GENRES.includes(g)) return g
  const direct = STYLE_GENRES.find(x => g.includes(x) || x.includes(g))
  if (direct) return direct
  const fuzzy = [
    [/玄幻奇幻|玄幻魔法|异世|异界/, '玄幻'],
    [/武侠修真|仙侠修真|修真/, '仙侠'],
    [/都市言情|都市异能|都市生活/, '都市'],
    [/女生|言情|古代言情|现代言情|浪漫/, '言情'],
    [/历史军事|架空历史|两宋元明/, '历史'],
    [/科幻灵异|科幻灵异|未来世界/, '科幻'],
    [/悬疑推理|侦探推理|灵异悬疑/, '悬疑'],
    [/西方奇幻|史诗奇幻|魔法奇幻/, '奇幻'],
    [/游戏竞技|虚拟网游|电子竞技/, '游戏'],
    [/现实百态|现实题材|官场商战/, '现实'],
    [/军事战争|军旅生涯|抗战烽火/, '军事'],
    [/二次元|原生幻想|搞笑吐槽/, '轻小说']
  ]
  for (const [re, target] of fuzzy) if (re.test(g)) return target
  return ''
}

/**
 * 按「分类 + 标题 + 简介」给作家文风打分推荐。
 * 分类命中给基础分（保证每类 3 位代表作家入围），标题/简介关键词与作家标签重合再加权，
 * 让同一分类下不同作品偏向不同作家。返回 top3 与一句话理由，供前端展示与一键采用。
 */
export function recommendStyles(novel, styles = AUTHOR_STYLES) {
  const genre = normalizeGenre(novel?.genre)
  const text = `${novel?.title || ''} ${novel?.synopsis || ''} ${novel?.style || ''}`.toLowerCase()
  const matched = KEYWORD_TAGS.filter(k => k.re.test(text))
  const tagSet = new Set(matched.flatMap(k => k.tags))
  const labels = matched.map(k => k.label)
  const canonical = new Set(GENRE_AUTHOR_MAP[genre] || [])

  const scored = styles
    .filter(s => s && s.id && s.prompt)
    .map(s => {
      const genres = s.genres || []
      const tags = s.tags || []
      const genreHit = genre && genres.includes(genre)
      const tagHits = tags.filter(t => tagSet.has(t))
      let score = 0
      if (genreHit) score += 4
      if (canonical.has(s.id)) score += 1
      score += tagHits.length * 2
      const reasons = []
      if (genreHit) reasons.push(`契合「${genre}」题材`)
      if (tagHits.length) reasons.push(`呼应简介中的「${labels.join('、')}」`)
      return { id: s.id, name: s.name, score, reason: reasons.join('，') || '通用文风备选' }
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)

  const picks = scored.slice(0, 3)
  return { genre, picks, top: picks[0]?.id || '' }
}

/** 解析作品实际生效的文风 id：'auto' 走题材自动推荐，具体 id 直接用，空值不套文风 */
export function resolveStyleId(novel) {
  const id = novel?.authorStyleId
  if (id && id !== 'auto') return id
  if (id === 'auto') return recommendStyles(novel).top
  return ''
}

