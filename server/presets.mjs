// ---------- 自定义库（作者自建，存于数据目录） ----------
export function makeCustomStore({ fs, dir, file, required }) {
  const path = file
  function read() {
    try {
      const data = JSON.parse(fs.readFileSync(path, 'utf8'))
      return Array.isArray(data) ? data : []
    } catch {
      // 主文件损坏时尝试备份，与 app.mjs 的 readJson 策略一致
      try {
        const bak = JSON.parse(fs.readFileSync(path + '.bak', 'utf8'))
        return Array.isArray(bak) ? bak : []
      } catch {
        return []
      }
    }
  }
  // 原子写入：临时文件 → fsync → 备份旧版 → 重命名（用户自建的文风/模板不因崩溃丢失）
  function write(list) {
    fs.mkdirSync(dir, { recursive: true })
    const tmp = `${path}.tmp`
    const text = JSON.stringify(list, null, 2)
    const fd = fs.openSync(tmp, 'w')
    try {
      fs.writeFileSync(fd, text, 'utf8')
      fs.fsyncSync(fd)
    } finally {
      fs.closeSync(fd)
    }
    try {
      if (fs.existsSync(path)) fs.copyFileSync(path, path + '.bak')
    } catch {
      /* 备份失败不阻塞写入 */
    }
    fs.renameSync(tmp, path)
  }
  function valid(item) {
    return item && required.every(k => (k === 'rules' ? Array.isArray(item.rules) && item.rules.length : item[k]))
  }
  return {
    list: read,
    save(item) {
      const list = read()
      const i = list.findIndex(x => x.id === item.id)
      if (i >= 0) list[i] = item
      else list.push(item)
      write(list)
      return item
    },
    remove(id) {
      write(read().filter(x => x.id !== id))
    },
    valid
  }
}
